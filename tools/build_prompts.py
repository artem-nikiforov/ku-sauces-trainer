OUT_DIR = os.path.join(COURSE, "assets", "scene")


def load_bible():
    if not os.path.exists(BIBLE):
        sys.exit("Не найдена библия стиля: " + BIBLE)
    return json.load(io.open(BIBLE, encoding="utf-8"))


